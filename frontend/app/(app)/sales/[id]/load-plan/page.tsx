'use client';

import { useEffect, useRef, useState } from 'react';
import { useParams } from 'next/navigation';
import { useTranslations } from 'next-intl';
import { DndContext, type DragEndEvent, PointerSensor, useDraggable, useDroppable, useSensor, useSensors } from '@dnd-kit/core';
import { useTransportUnitTypes } from '@/lib/hooks/use-logistics';
import { useLoadPlan, useGenerateLoadPlan, useMoveLoadPlanItem } from '@/lib/hooks/use-sales';
import { useApiErrorMessage } from '@/lib/api-error-message';
import type { LoadPlanTruck, LoadPlanTruckItem } from '@/lib/api-client/sales';
import { updateAssembly } from '@/lib/api-client/bom';
import { listFilesForEntities } from '@/lib/api-client/files';
import { useFilesForEntities } from '@/lib/hooks/use-files';
import { isGlbFile } from '@/components/domain/files/entity-documents-field';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Select, SelectTrigger, SelectValue, SelectContent, SelectItem } from '@/components/ui/select';
import { LoadingBlock } from '@/components/ui/loading-block';
import { RequirePermission } from '@/components/domain/auth/require-permission';
import { AssemblyCell } from '@/components/domain/sales/assembly-cell';
import { TruckLoadViewer, colorForAssembly } from '@/components/domain/sales/truck-load-viewer';

type BulkFillStatus = 'done' | 'no-model' | 'error';

export default function LoadPlanPage() {
  const { id: orderId } = useParams<{ id: string }>();
  const t = useTranslations('sales');
  const tc = useTranslations('common');
  const apiErrorMessage = useApiErrorMessage();

  const { data: transportTypes, isLoading: typesLoading } = useTransportUnitTypes();
  const { data: plan, isLoading: planLoading } = useLoadPlan(orderId);
  const generatePlan = useGenerateLoadPlan(orderId);
  const moveItem = useMoveLoadPlanItem(orderId);

  const sizedTypes = (transportTypes ?? []).filter((tp) => tp.active && tp.lengthCm && tp.widthCm && tp.heightCm);

  const [selectedTypeId, setSelectedTypeId] = useState<string | undefined>(undefined);
  const [selectedTruckIndex, setSelectedTruckIndex] = useState<number | null>(null);
  // "план завантаження мав на увазі що самі глб файли в 3д переглядачі
  // малі" (2026-10-28) — clicking a legend item zooms the 3D view in on
  // just that one assembly's own box(es) instead of the whole truck's
  // cargo; clicking the same one again (or switching trucks) goes back to
  // the full-load view.
  const [focusedAssemblyId, setFocusedAssemblyId] = useState<string | null>(null);
  const [generateError, setGenerateError] = useState<string | null>(null);
  const [bulkFilling, setBulkFilling] = useState(false);
  const [bulkResults, setBulkResults] = useState<Record<string, BulkFillStatus> | null>(null);
  const skippedAssemblies = plan?.skippedAssemblies ?? [];
  // Only `missing-packaging` lines can be helped by measuring a 3D model —
  // a `does-not-fit` line already HAS box dimensions, they're just bigger
  // than the chosen truck type's own envelope/weight limit, so recomputing
  // from the GLB wouldn't change anything; the fix there is picking a
  // bigger transport type or physically repackaging, not remeasuring.
  const missingAssemblies = skippedAssemblies.filter((a) => a.reason === 'missing-packaging');
  const doesNotFitAssemblies = skippedAssemblies.filter((a) => a.reason === 'does-not-fit');

  useEffect(() => {
    if (!selectedTypeId && plan) setSelectedTypeId(plan.transportUnitTypeId);
    else if (!selectedTypeId && sizedTypes.length > 0) setSelectedTypeId(sizedTypes[0].id);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [plan, sizedTypes.length]);

  // "за замовчуванням... обирало в фури завантаження" (2026-10-28): auto-
  // generate on first open if there's no plan yet and a usable transport
  // type exists — the user shouldn't have to press anything to see a plan.
  // `hasAutoGeneratedRef` fires this AT MOST ONCE per page visit — a real
  // production incident (2026-10-28) had this re-fire on every failed
  // attempt (isPending cycling true/false without `plan` ever becoming
  // truthy kept flipping the old boolean dependency back to "eligible"),
  // flooding the backend with retries until it exhausted the DB connection
  // pool and took down unrelated endpoints too. A failed auto-generate now
  // just shows `generateError` with a manual "Перерахувати" retry button.
  const hasAutoGeneratedRef = useRef(false);
  useEffect(() => {
    if (hasAutoGeneratedRef.current) return;
    if (!planLoading && !plan && selectedTypeId) {
      hasAutoGeneratedRef.current = true;
      handleGenerate();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [planLoading, plan, selectedTypeId]);

  useEffect(() => {
    if (plan && plan.trucks.length > 0 && selectedTruckIndex == null) setSelectedTruckIndex(plan.trucks[0].index);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [plan]);

  async function handleGenerate() {
    if (!selectedTypeId) return;
    setGenerateError(null);
    setBulkResults(null);
    try {
      await generatePlan.mutateAsync(selectedTypeId);
    } catch (err) {
      setGenerateError(apiErrorMessage(err, tc('error')));
    }
  }

  // "хай план всерівно генерує але без урахування того що нема і пише що
  // план згенеровано без урахування цих позицій через відсутність розмірів"
  // (2026-10-28): generate() no longer blocks on missing packaging — it
  // leaves those lines out and `get()` reports them back as
  // `skippedAssemblies` every time, live, whether or not they've just been
  // regenerated. "у нас же є модель кожного виробу": rather than sending
  // the user to click through every one of those assemblies' own BOM card
  // one at a time (PackagingDimensionsFromModelCalculator there does the
  // same computation for a single assembly), this does it for all of them
  // at once — looks up each one's attached .glb (ASSEMBLY_DOCUMENT),
  // measures it, and saves the result directly. Assemblies with no .glb
  // attached are reported as `no-model` so the user knows exactly which
  // ones still need a manual measurement, instead of a silent partial
  // success. Re-generates once every assembly succeeded, so the newly-
  // packaged lines join the plan.
  async function handleBulkFillFromModels() {
    if (missingAssemblies.length === 0) return;
    setBulkFilling(true);
    const results: Record<string, BulkFillStatus> = {};
    try {
      const filesByEntity = await listFilesForEntities(
        'Assembly',
        missingAssemblies.map((a) => a.id),
        'ASSEMBLY_DOCUMENT',
      );
      const { computeGlbDimensions } = await import('@/components/domain/files/step-3d-viewer');
      for (const assembly of missingAssemblies) {
        const glbFile = (filesByEntity[assembly.id] ?? []).find((f) => isGlbFile(f.originalName));
        if (!glbFile) {
          results[assembly.id] = 'no-model';
          continue;
        }
        try {
          const dims = await computeGlbDimensions(glbFile.downloadUrl);
          if (!dims) {
            results[assembly.id] = 'no-model';
            continue;
          }
          await updateAssembly(assembly.id, {
            boxLengthCm: Math.round(dims.lengthCm * 10) / 10,
            boxWidthCm: Math.round(dims.widthCm * 10) / 10,
            boxHeightCm: Math.round(dims.heightCm * 10) / 10,
          });
          results[assembly.id] = 'done';
        } catch {
          results[assembly.id] = 'error';
        }
      }
    } finally {
      setBulkResults(results);
      setBulkFilling(false);
    }
    if (missingAssemblies.every((a) => results[a.id] === 'done')) {
      handleGenerate();
    }
  }

  const sensors = useSensors(useSensor(PointerSensor, { activationConstraint: { distance: 4 } }));

  function handleDragEnd(event: DragEndEvent) {
    const { active, over } = event;
    if (!over) return;
    const toTruckIndex = Number(String(over.id).replace('truck-', ''));
    const itemId = String(active.id).replace('item-', '');
    const fromTruck = plan?.trucks.find((tr) => tr.items.some((i) => i.id === itemId));
    if (!fromTruck || fromTruck.index === toTruckIndex) return;
    moveItem.mutate({ itemId, toTruckIndex });
  }

  const selectedTruck = plan?.trucks.find((tr) => tr.index === selectedTruckIndex) ?? null;
  // Used to prefetch EVERY truck's assemblies' .glb urls up front (so
  // switching trucks doesn't refetch) — deliberately NOT what the legend
  // below renders, see `selectedTruckAssemblyNames`.
  const assemblyNames = new Map<string, string>();
  for (const truck of plan?.trucks ?? []) for (const item of truck.items) assemblyNames.set(item.assemblyId, item.assemblyName);
  // The legend/focus-camera UI must only ever show assemblies actually IN
  // the currently selected truck — using the all-trucks map above there
  // let a legend entry point at an assembly that lives in a DIFFERENT
  // truck, so clicking it to "focus the camera" silently found nothing in
  // the visible truck's own placedBoxes and did nothing (2026-10-28, found
  // live: clicking "Antrieb_VBG" while Фура №1 was selected had no visible
  // effect — it was actually packed into Фура №2).
  const selectedTruckAssemblyNames = new Map<string, string>();
  for (const item of selectedTruck?.items ?? []) selectedTruckAssemblyNames.set(item.assemblyId, item.assemblyName);
  const planTransportType = plan ? (transportTypes ?? []).find((tp) => tp.id === plan.transportUnitTypeId) : undefined;
  const truckDims = planTransportType
    ? { lengthCm: Number(planTransportType.lengthCm), widthCm: Number(planTransportType.widthCm), heightCm: Number(planTransportType.heightCm) }
    : { lengthCm: 0, widthCm: 0, heightCm: 0 };

  // "в самій 3д моделі завантаження де є глб має бути видно 3д моделі що
  // там" (2026-10-28): resolve each assembly's attached .glb once per page
  // (not per truck) so TruckLoadViewer can swap a plain colored block for
  // the actual model.
  const assemblyIds = [...assemblyNames.keys()];
  const { data: assemblyGlbFiles } = useFilesForEntities('Assembly', assemblyIds, 'ASSEMBLY_DOCUMENT');
  const assemblyGlbUrls: Record<string, string> = {};
  for (const [assemblyId, files] of Object.entries(assemblyGlbFiles ?? {})) {
    const glb = files.find((f) => isGlbFile(f.originalName));
    if (glb) assemblyGlbUrls[assemblyId] = glb.downloadUrl;
  }

  return (
    <RequirePermission permission="shipments:manage" redirectTo={`/sales/${orderId}`}>
      <div className="space-y-4">
        <h1 className="text-xl font-semibold">{t('loadPlanTitle')}</h1>

        <Card>
          <CardHeader>
            <CardTitle className="text-base">{t('loadPlanTransportType')}</CardTitle>
          </CardHeader>
          <CardContent className="flex flex-wrap items-end gap-3">
            {typesLoading ? (
              <LoadingBlock />
            ) : sizedTypes.length === 0 ? (
              <p className="text-sm text-muted-foreground">{t('loadPlanNoSizedTypes')}</p>
            ) : (
              <>
                <div className="space-y-1.5">
                  <Select value={selectedTypeId} onValueChange={setSelectedTypeId}>
                    <SelectTrigger className="w-64">
                      <SelectValue />
                    </SelectTrigger>
                    <SelectContent>
                      {sizedTypes.map((tp) => (
                        <SelectItem key={tp.id} value={tp.id}>
                          {tp.name}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>
                <Button onClick={handleGenerate} loading={generatePlan.isPending} disabled={!selectedTypeId}>
                  {t('loadPlanRegenerate')}
                </Button>
              </>
            )}
          </CardContent>
          {generateError && (
            <CardContent className="pt-0">
              <p className="text-sm text-destructive">{generateError}</p>
            </CardContent>
          )}
        </Card>

        {missingAssemblies.length > 0 && (
          <Card>
            <CardHeader>
              <CardTitle className="text-base">{t('loadPlanMissingPackagingTitle')}</CardTitle>
            </CardHeader>
            <CardContent className="space-y-3">
              <p className="text-sm text-amber-600 dark:text-amber-500">{t('loadPlanSkippedWarning')}</p>
              <ul className="space-y-1 text-sm">
                {missingAssemblies.map((a) => {
                  const status = bulkResults?.[a.id];
                  return (
                    <li key={a.id} className="flex items-center justify-between gap-2">
                      <span>{a.name}</span>
                      {status === 'done' && <span className="text-xs text-emerald-600 dark:text-emerald-500">{t('loadPlanBulkFillDone')}</span>}
                      {status === 'no-model' && <span className="text-xs text-amber-600 dark:text-amber-500">{t('loadPlanBulkFillNoModel')}</span>}
                      {status === 'error' && <span className="text-xs text-destructive">{tc('error')}</span>}
                    </li>
                  );
                })}
              </ul>
              <Button type="button" onClick={handleBulkFillFromModels} loading={bulkFilling}>
                {t('loadPlanBulkFillFromModels')}
              </Button>
            </CardContent>
          </Card>
        )}

        {doesNotFitAssemblies.length > 0 && (
          <Card>
            <CardHeader>
              <CardTitle className="text-base">{t('loadPlanDoesNotFitTitle')}</CardTitle>
            </CardHeader>
            <CardContent className="space-y-3">
              <p className="text-sm text-amber-600 dark:text-amber-500">{t('loadPlanDoesNotFitWarning')}</p>
              <ul className="space-y-1 text-sm">
                {doesNotFitAssemblies.map((a) => (
                  <li key={a.id}>{a.name}</li>
                ))}
              </ul>
            </CardContent>
          </Card>
        )}

        {planLoading || generatePlan.isPending ? (
          <LoadingBlock />
        ) : !plan ? (
          sizedTypes.length === 0 ? null : <p className="text-sm text-muted-foreground">{t('loadPlanEmpty')}</p>
        ) : (
          <DndContext sensors={sensors} onDragEnd={handleDragEnd}>
            <div className="flex gap-3 overflow-x-auto pb-2">
              {plan.trucks.map((truck) => (
                <TruckColumn
                  key={truck.id}
                  truck={truck}
                  selected={truck.index === selectedTruckIndex}
                  onSelect={() => {
                    setSelectedTruckIndex(truck.index);
                    setFocusedAssemblyId(null);
                  }}
                />
              ))}
              <TruckColumn
                truck={{ id: 'new', index: (plan.trucks.at(-1)?.index ?? 0) + 1, items: [], placedBoxes: [], overflowBoxCount: 0, totalWeightKg: 0, volumeUsedPercent: 0 }}
                selected={false}
                onSelect={() => {}}
                isNewDropZone
              />
            </div>

            {selectedTruck && (
              <Card>
                <CardHeader>
                  <CardTitle className="text-base">
                    {t('loadPlanTruckNumber', { index: selectedTruck.index })} — {selectedTruck.totalWeightKg.toFixed(1)} {t('kgUnit')},{' '}
                    {selectedTruck.volumeUsedPercent.toFixed(0)}% {t('loadPlanVolumeUsed')}
                  </CardTitle>
                </CardHeader>
                <CardContent className="space-y-3">
                  {selectedTruck.overflowBoxCount > 0 && (
                    <p className="text-sm text-amber-600 dark:text-amber-500">{t('loadPlanOverflowWarning', { count: selectedTruck.overflowBoxCount })}</p>
                  )}
                  <TruckLoadViewer
                    truckDims={truckDims}
                    placedBoxes={selectedTruck.placedBoxes}
                    assemblyGlbUrls={assemblyGlbUrls}
                    focusedAssemblyId={focusedAssemblyId}
                  />
                  {focusedAssemblyId && (
                    <p className="text-xs text-muted-foreground">
                      {t('loadPlanFocusedHint')}{' '}
                      <button type="button" className="underline" onClick={() => setFocusedAssemblyId(null)}>
                        {t('loadPlanShowWholeLoad')}
                      </button>
                    </p>
                  )}
                  <div className="flex flex-wrap gap-3">
                    {[...selectedTruckAssemblyNames.entries()].map(([assemblyId, name]) => (
                      <button
                        type="button"
                        key={assemblyId}
                        onClick={() => setFocusedAssemblyId((prev) => (prev === assemblyId ? null : assemblyId))}
                        className={`flex w-28 flex-col items-center gap-1.5 rounded-md p-1 text-center text-xs ${
                          focusedAssemblyId === assemblyId ? 'bg-accent ring-1 ring-primary' : 'hover:bg-accent'
                        }`}
                      >
                        <LegendSwatch assemblyId={assemblyId} glbUrl={assemblyGlbUrls[assemblyId]} />
                        <span className="line-clamp-2">{name}</span>
                      </button>
                    ))}
                  </div>
                </CardContent>
              </Card>
            )}
          </DndContext>
        )}
      </div>
    </RequirePermission>
  );
}

/**
 * Legend swatch (2026-10-28, "неипоказує там реальні глб вироби просто
 * прямокутники") — the shared 3D truck scene has to fit the WHOLE load in
 * one camera, so a single item can still end up tiny/hard to read when
 * cargo is spread across most of the truck's length (no per-item zoom
 * there). This renders a proper close-up snapshot of the item's own .glb
 * (same `captureGlbSnapshot` framing Step3DViewer itself proves legible —
 * camera distance scaled to THAT item alone, not diluted by the rest of
 * the load) right next to its name, so what's actually loaded is always
 * recognizable regardless of truck-scene zoom. Falls back to the plain
 * color dot for assemblies with no attached .glb.
 */
function LegendSwatch({ assemblyId, glbUrl }: { assemblyId: string; glbUrl?: string }) {
  const [snapshot, setSnapshot] = useState<string | null>(null);
  useEffect(() => {
    if (!glbUrl) return;
    let cancelled = false;
    import('@/components/domain/files/step-3d-viewer').then(({ captureGlbSnapshot }) =>
      captureGlbSnapshot(glbUrl).then((dataUrl) => {
        if (!cancelled) setSnapshot(dataUrl);
      }),
    );
    return () => {
      cancelled = true;
    };
  }, [glbUrl]);

  if (snapshot) {
    // eslint-disable-next-line @next/next/no-img-element
    return <img src={snapshot} alt="" className="h-20 w-20 rounded-md border border-border bg-card object-contain" />;
  }
  return <span className="h-20 w-20 rounded-md" style={{ backgroundColor: colorForAssembly(assemblyId) }} />;
}

function TruckColumn({
  truck,
  selected,
  onSelect,
  isNewDropZone,
}: {
  truck: LoadPlanTruck;
  selected: boolean;
  onSelect: () => void;
  isNewDropZone?: boolean;
}) {
  const t = useTranslations('sales');
  const { setNodeRef, isOver } = useDroppable({ id: `truck-${truck.index}` });

  return (
    <div
      ref={setNodeRef}
      onClick={onSelect}
      className={`flex w-56 shrink-0 flex-col gap-2 rounded-md border p-2 transition-colors ${
        selected ? 'border-primary' : 'border-border'
      } ${isOver ? 'bg-accent' : ''} ${isNewDropZone ? 'border-dashed' : ''} cursor-pointer`}
    >
      <p className="text-sm font-medium">
        {isNewDropZone ? t('loadPlanNewTruck') : t('loadPlanTruckNumber', { index: truck.index })}
      </p>
      {!isNewDropZone && <p className="text-xs text-muted-foreground">{truck.totalWeightKg.toFixed(1)} {t('kgUnit')}</p>}
      <div className="flex flex-col gap-1.5">
        {truck.items.map((item) => (
          <DraggableItemCard key={item.id} item={item} />
        ))}
      </div>
    </div>
  );
}

function DraggableItemCard({ item }: { item: LoadPlanTruckItem }) {
  const t = useTranslations('sales');
  const { attributes, listeners, setNodeRef, transform, isDragging } = useDraggable({ id: `item-${item.id}` });
  const style = transform ? { transform: `translate3d(${transform.x}px, ${transform.y}px, 0)`, zIndex: 10 } : undefined;

  return (
    <div
      ref={setNodeRef}
      style={style}
      {...listeners}
      {...attributes}
      className={`cursor-grab rounded border border-border bg-card p-1.5 text-xs shadow-sm active:cursor-grabbing ${isDragging ? 'opacity-50' : ''}`}
    >
      <AssemblyCell assemblyId={item.assemblyId} size="sm" textClassName="text-xs font-medium" />
      <p className="mt-1 text-muted-foreground">
        {t('transportUnitsCount', { count: item.unitsQty })} · {item.weightKg.toFixed(1)} {t('kgUnit')}
      </p>
    </div>
  );
}
